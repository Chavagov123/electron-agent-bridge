// Bundle the session frame preload (src/preload/renderer-ipc.ts) into one CommonJS script and expose
// it as a string module: src/generated/preload-source.ts. The runtime writes it to the private
// endpoint directory and registers it on every session, so it works however the app is bundled.
// Generated, git-ignored; run by `pnpm gen`.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

/** It runs in every page: keep it small. */
const BUDGET_BYTES = 12 * 1024;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  entryPoints: [join(root, 'src', 'preload', 'renderer-ipc.ts')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'node',
  target: 'chrome120',
  minify: true,
  // Sandboxed preloads can require `electron` and nothing else.
  external: ['electron'],
  conditions: ['@eab/source'],
  logLevel: 'warning',
  metafile: true,
});
const source = result.outputFiles[0]?.text ?? '';
const requires = [...source.matchAll(/require\(["']([^"']+)["']\)/g)].map((match) => match[1]);
const foreign = requires.filter((name) => name !== 'electron');
if (foreign.length > 0) throw new Error(`preload requires ${foreign.join(', ')}; only electron is allowed`);
if (Buffer.byteLength(source) > BUDGET_BYTES) {
  throw new Error(`preload is ${Buffer.byteLength(source)} bytes, over the ${BUDGET_BYTES}-byte budget`);
}
const version = createHash('sha256').update(source).digest('hex').slice(0, 12);
const outFile = join(root, 'src', 'generated', 'preload-source.ts');
const content =
  '// Generated by packages/electron/scripts/build-preload.mjs from src/preload. Do not edit.\n' +
  `/** Hash of the preload bundle (also its file name). */\n` +
  `export const PRELOAD_VERSION = ${JSON.stringify(version)};\n` +
  `/** The session frame preload as a self-contained script (${Buffer.byteLength(source)} bytes). */\n` +
  `export const PRELOAD_SOURCE: string = ${JSON.stringify(source)};\n`;
mkdirSync(dirname(outFile), { recursive: true });
let previous = '';
try {
  previous = readFileSync(outFile, 'utf8');
} catch {
  // First run.
}
if (previous !== content) writeFileSync(outFile, content);
console.log(`preload: ${Buffer.byteLength(source)} bytes, version ${version}`);

// The source-map worker (src/logs/source-map-worker.ts) as one script, run with `new Worker(source,
// {eval: true})` from src/generated/source-map-worker-source.ts.
const worker = await build({
  entryPoints: [join(root, 'src', 'logs', 'source-map-worker.ts')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'node',
  target: 'node20',
  minify: true,
  conditions: ['@eab/source'],
  logLevel: 'warning',
});
const workerSource = worker.outputFiles[0]?.text ?? '';
const workerRequires = [...workerSource.matchAll(/require\(["']([^"']+)["']\)/g)].map((match) => match[1]);
const notBuiltin = workerRequires.filter((name) => !name.startsWith('node:'));
if (notBuiltin.length > 0) throw new Error(`source-map worker requires ${notBuiltin.join(', ')}`);
const workerFile = join(root, 'src', 'generated', 'source-map-worker-source.ts');
const workerContent =
  '// Generated by packages/electron/scripts/build-preload.mjs from src/logs/source-map-worker.ts. Do not edit.\n' +
  `/** The source-map worker as a self-contained script (${Buffer.byteLength(workerSource)} bytes). */\n` +
  `export const SOURCE_MAP_WORKER_SOURCE: string = ${JSON.stringify(workerSource)};\n`;
let previousWorker = '';
try {
  previousWorker = readFileSync(workerFile, 'utf8');
} catch {
  // First run.
}
if (previousWorker !== workerContent) writeFileSync(workerFile, workerContent);
console.log(`source-map worker: ${Buffer.byteLength(workerSource)} bytes`);
