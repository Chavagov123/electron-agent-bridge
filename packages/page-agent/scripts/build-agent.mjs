// Bundle the in-page agent (src/agent/entry.ts) and the main-world state hook (src/state/entry.ts) into
// self-contained scripts and expose them as string modules in src/generated/. The engine injects the
// agent into each page's isolated world and the hook into its main world. Generated, git-ignored; run
// by `pnpm gen` (and by build/test/typecheck/lint).
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

/** Size budgets: both run in every page and must stay small. */
const AGENT_BUDGET_BYTES = 45 * 1024;
const STATE_HOOK_BUDGET_BYTES = 9 * 1024;
/** Sent on demand only (state.component), but still in every such call. */
const COMPONENT_READER_BUDGET_BYTES = 8 * 1024;

const PLACEHOLDER = '__eab_agent_version_placeholder__';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

async function bundle(entry, options = {}) {
  const result = await build({
    entryPoints: [join(root, 'src', ...entry)],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'chrome120',
    minify: true,
    conditions: ['@electron-agent-bridge/source'],
    logLevel: 'warning',
    ...options,
  });
  return result.outputFiles[0]?.text ?? '';
}

function checkBudget(name, source, budget) {
  const bytes = Buffer.byteLength(source);
  if (bytes > budget) throw new Error(`${name} is ${bytes} bytes, over the ${budget}-byte budget`);
  return bytes;
}

function writeIfChanged(file, content) {
  const outFile = join(root, 'src', 'generated', file);
  mkdirSync(dirname(outFile), { recursive: true });
  let previous = '';
  try {
    previous = readFileSync(outFile, 'utf8');
  } catch {
    // First generation.
  }
  if (previous !== content) writeFileSync(outFile, content);
}

const firstPass = await bundle(['agent', 'entry.ts'], {
  define: { __EAB_AGENT_VERSION__: JSON.stringify(PLACEHOLDER) },
});
const version = createHash('sha256').update(firstPass).digest('hex').slice(0, 12);
const agent = firstPass.replaceAll(JSON.stringify(PLACEHOLDER), JSON.stringify(version));
const agentBytes = checkBudget('page agent', agent, AGENT_BUDGET_BYTES);
writeIfChanged(
  'agent-source.ts',
  '// Generated by packages/page-agent/scripts/build-agent.mjs from src/agent. Do not edit.\n' +
    `/** Hash of the agent bundle; changes whenever the agent changes. */\n` +
    `export const AGENT_VERSION = ${JSON.stringify(version)};\n` +
    `/** The agent as a self-contained script for an isolated world (${agentBytes} bytes). */\n` +
    `export const AGENT_SOURCE: string = ${JSON.stringify(agent)};\n`,
);

// `var eabStateHook = …` is kept local by the wrapper in state-hook.ts.
const hook = await bundle(['state', 'entry.ts'], { globalName: 'eabStateHook' });
const hookBytes = checkBudget('state hook', hook, STATE_HOOK_BUDGET_BYTES);
writeIfChanged(
  'state-hook-source.ts',
  '// Generated by packages/page-agent/scripts/build-agent.mjs from src/state. Do not edit.\n' +
    `/** The state hook bundle (${hookBytes} bytes); defines \`eabStateHook.install(config)\`. */\n` +
    `export const STATE_HOOK_BUNDLE: string = ${JSON.stringify(hook)};\n`,
);

// Defines `eabComponentReader.read(el, request)`; wrapped as a function declaration by component-reader.ts.
const reader = await bundle(['component', 'entry.ts'], { globalName: 'eabComponentReader' });
const readerBytes = checkBudget('component reader', reader, COMPONENT_READER_BUDGET_BYTES);
writeIfChanged(
  'component-reader-source.ts',
  '// Generated by packages/page-agent/scripts/build-agent.mjs from src/component. Do not edit.\n' +
    `/** The component reader bundle (${readerBytes} bytes); defines \`eabComponentReader.read\`. */\n` +
    `export const COMPONENT_READER_BUNDLE: string = ${JSON.stringify(reader)};\n`,
);
